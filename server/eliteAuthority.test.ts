import test from 'node:test';
import assert from 'node:assert/strict';
import { RoomAuthority } from './authority';
import type { RoomSession, RoomAction, DriverProfile } from '../shared/protocol';
import { ELITE_COURSE_VERSION } from '../shared/eliteCourse';
import { eliteWindow } from '../src/game/elite';
const profile = (id: string): DriverProfile => ({ driverId: id, stats: { offered: 0, accepted: 0, cancelled: 0, completedTrips: 0, acceptanceRate: 1, cancellationRate: 0, updatedAt: 1800000000000 }, eliteCertification: { assessmentId: `cert-${id}`, courseVersion: ELITE_COURSE_VERSION, certifiedAt: 1800000000000 } });
test('two certified drivers share one scheduled passenger claim, retry exactly once, and restore the frozen qualification', async () => {
    let now = 1800000000000, authority = new RoomAuthority({ now: () => now, blindOrders: true });
    const host = await authority.createRoom({ nickname: 'Elite A', featureVersion: '0.6', vehicleCatalogVersion: 1, advancedRulesVersion: 1, blindOrdersVersion: 1, rules: { speed: 60, shiftDurationMinutes: 360 }, setup: { vehicleId: 'alphard-hybrid' } }), guest = await authority.joinRoom(host.roomCode, { nickname: 'Elite B', featureVersion: '0.6', vehicleCatalogVersion: 1, advancedRulesVersion: 1, blindOrdersVersion: 1, setup: { vehicleId: 'vellfire-hybrid' } });
    authority.attachDriver(host.roomCode, host.playerId, profile('a'));
    authority.attachDriver(host.roomCode, guest.playerId, profile('b'));
    const saved = JSON.parse(authority.serializeRoom(host.roomCode)!);
    saved.metadata.room.seed = 0;
    authority = new RoomAuthority({ now: () => now, blindOrders: true });
    authority.deserializeRoom(JSON.stringify(saved));
    const seq = new Map<string, number>();
    const send = (s: RoomSession, action: RoomAction) => authority.handleCommand(s.roomCode, s.resumeToken, { seq: (seq.set(s.playerId, (seq.get(s.playerId) || 0) + 1), seq.get(s.playerId)!), action });
    await send(host, { type: 'ready', ready: true });
    await send(guest, { type: 'ready', ready: true });
    const loading = await send(host, { type: 'start' });
    const epoch = loading.room.loading!.epoch;
    await send(host, { type: 'map-ready', epoch, ready: true });
    await send(guest, { type: 'map-ready', epoch, ready: true });
    now += 3000;
    await authority.readSnapshot(host.roomCode, host.resumeToken);
    now += (eliteWindow(0, 0)!.announcedAt + .1) * 1000;
    const a = await authority.readSnapshot(host.roomCode, host.resumeToken), b = await authority.readSnapshot(guest.roomCode, guest.resumeToken);
    const booking = a.ownState!.eliteReservations!.find(item => item.status === 'available')!;
    assert.ok(booking);
    assert.ok(b.ownState!.eliteReservations!.some(item => item.id === booking.id));
    assert.equal(booking.offer.destination.id, 'withheld-destination');
    assert.equal(booking.offer.estimatedFare, 0);
    const accepted = await send(host, { type: 'elite-booking', bookingId: booking.id, choice: 'accept' });
    assert.equal(accepted.ownState!.acceptedOffers, 1);
    const retry = await authority.handleCommand(host.roomCode, host.resumeToken, { seq: seq.get(host.playerId)!, action: { type: 'elite-booking', bookingId: booking.id, choice: 'accept' } });
    assert.equal(retry.ownState!.acceptedOffers, 1);
    await assert.rejects(() => send(guest, { type: 'elite-booking', bookingId: booking.id, choice: 'accept' }), (e: any) => e.code === 'offer_taken');
    const other = await authority.readSnapshot(guest.roomCode, guest.resumeToken);
    assert.equal(other.ownState!.eliteReservations!.find(item => item.id === booking.id)!.status, 'unavailable');
    assert.equal(other.ownState!.acceptedOffers, 0);
    assert.equal(other.ownState!.declinedOffers, 0);
    const cold = new RoomAuthority({ now: () => now });
    cold.deserializeRoom(authority.serializeRoom(host.roomCode)!);
    const restored = await cold.readSnapshot(host.roomCode, host.resumeToken);
    assert.equal(restored.ownState!.eliteCertified, true);
    assert.equal(restored.ownState!.eliteReservations!.find(item => item.id === booking.id)!.status, 'accepted');
    assert.equal(restored.ownState!.acceptedOffers, 1);
});
